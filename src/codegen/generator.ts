/**
 * TypeScript code generator.
 *
 * Transforms a {@link ParsedSpec} into ready-to-write TypeScript source files:
 * - `types.ts`  — interfaces from schema definitions
 * - `client.ts` — typed client class extending BannerApiClient
 */

import type { ParsedEndpoint, ParsedSchema, ParsedSchemaProperty, ParsedSpec } from "./parser.js";

// ── Public types ──

export interface GeneratedFiles {
  /** TypeScript source for schema interfaces. */
  types: string;
  /** TypeScript source for the API client class. */
  client: string;
}

// ── Public API ──

/**
 * Generate TypeScript source files from a parsed OpenAPI spec.
 *
 * @param spec   — the parsed intermediate representation
 * @param apiName — class name prefix (e.g. "StudentApi" → StudentApiClient).
 *                  Defaults to the spec title.
 */
export function generateClient(spec: ParsedSpec, apiName?: string): GeneratedFiles {
  const name = sanitizeClassName(apiName ?? spec.title);
  const className = name.endsWith("Client") ? name : `${name}Client`;

  const types = generateTypes(spec.schemas);
  const client = generateClientClass(spec, className);

  return { types, client };
}

// ── Types generation ──

function generateTypes(schemas: Map<string, ParsedSchema>): string {
  const lines: string[] = ["// Auto-generated by ellucian-banner-codegen — do not edit", ""];

  for (const [name, schema] of schemas) {
    lines.push(...generateInterface(name, schema));
    lines.push("");
  }

  return lines.join("\n");
}

function generateInterface(name: string, schema: ParsedSchema): string[] {
  const interfaceName = toPascalCase(name);
  const lines: string[] = [];

  lines.push(`export interface ${interfaceName} {`);

  if (schema.properties) {
    for (const [propName, prop] of schema.properties) {
      if (prop.description) {
        lines.push(`  /** ${sanitizeComment(prop.description)} */`);
      }
      const optional = prop.required ? "" : "?";
      const tsType = propToTsType(prop);
      lines.push(`  ${propertyKey(propName)}${optional}: ${tsType};`);
    }
  }

  lines.push("}");
  return lines;
}

function propToTsType(prop: ParsedSchemaProperty): string {
  if (prop.ref) {
    return toPascalCase(prop.ref);
  }
  if (prop.type === "array") {
    if (prop.items?.ref) {
      return `${toPascalCase(prop.items.ref)}[]`;
    }
    const itemType = prop.items ? schemaToTsType(prop.items) : "unknown";
    return `${itemType}[]`;
  }
  return mapPrimitiveType(prop.type);
}

function schemaToTsType(schema: ParsedSchema): string {
  if (schema.ref) return toPascalCase(schema.ref);
  if (schema.type === "array") {
    const itemType = schema.items ? schemaToTsType(schema.items) : "unknown";
    return `${itemType}[]`;
  }
  return mapPrimitiveType(schema.type);
}

function mapPrimitiveType(type: string): string {
  switch (type) {
    case "string":
      return "string";
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "object":
      return "Record<string, unknown>";
    default:
      return "unknown";
  }
}

// ── Client generation ──

function generateClientClass(spec: ParsedSpec, className: string): string {
  const schemaNames = new Set<string>();
  collectUsedSchemaNames(spec, schemaNames);

  const typeImports = [...schemaNames].sort().map((n) => toPascalCase(n));

  const lines: string[] = [
    "// Auto-generated by ellucian-banner-codegen — do not edit",
    "",
    'import { BannerApiClient } from "ellucian-banner";',
    'import type { RequestOptions } from "ellucian-banner";',
  ];

  if (typeImports.length > 0) {
    lines.push(`import type { ${typeImports.join(", ")} } from "./types.js";`);
  }

  lines.push("");
  lines.push(`export class ${className} extends BannerApiClient {`);
  lines.push(`  /** Base path from the spec; used by BannerClient.use(). */`);
  lines.push(
    `  static readonly basePath = ${JSON.stringify(spec.basePath === "/" ? "" : spec.basePath)};`,
  );

  // Names a generated method must never take: BannerApiClient members (an
  // override such as `get()` would have an incompatible signature and call
  // itself) plus Object/class built-ins.
  const usedNames = new Set<string>(RESERVED_MEMBER_NAMES);
  for (const endpoint of spec.endpoints) {
    lines.push(...generateMethod(endpoint, usedNames));
  }

  lines.push("}");
  lines.push("");

  return lines.join("\n");
}

/** BannerApiClient members and other names generated methods must avoid. */
const RESERVED_MEMBER_NAMES = [
  "get",
  "post",
  "put",
  "patch",
  "delete",
  "getRaw",
  "withQuery",
  "url",
  "http",
  "basePath",
  "constructor",
  "prototype",
  "toString",
  "valueOf",
  "hasOwnProperty",
  "isPrototypeOf",
  "propertyIsEnumerable",
  "toLocaleString",
  "__proto__",
];

/** A method name not in `used`: suffix "Op", then a counter, on conflict. */
function uniqueMethodName(base: string, used: Set<string>): string {
  let name = used.has(base) ? `${base}Op` : base;
  for (let n = 2; used.has(name); n++) name = `${base}Op${n}`;
  used.add(name);
  return name;
}

function generateMethod(endpoint: ParsedEndpoint, usedNames: Set<string>): string[] {
  const methodName = uniqueMethodName(deriveMethodName(endpoint), usedNames);
  const pathParams = endpoint.parameters.filter((p) => p.in === "path");
  const queryParams = endpoint.parameters.filter((p) => p.in === "query");
  const httpMethod = endpoint.method;
  const acceptsBody = ["post", "put", "patch"].includes(httpMethod);
  const hasBody = !!endpoint.requestBody && acceptsBody;
  const returnType = deriveReturnType(endpoint);

  // Build parameter list
  const params: string[] = [];
  for (const p of pathParams) {
    params.push(`${toIdentifier(p.name)}: ${mapPrimitiveType(p.type)}`);
  }
  if (hasBody) {
    const bodyType = endpoint.requestBody?.ref
      ? toPascalCase(endpoint.requestBody.ref)
      : endpoint.requestBody
        ? schemaToTsType(endpoint.requestBody)
        : "unknown";
    params.push(`body: ${bodyType}`);
  }
  if (queryParams.length > 0) {
    const queryType = buildQueryParamsType(queryParams);
    const allOptional = queryParams.every((p) => !p.required);
    params.push(`query${allOptional ? "?" : ""}: ${queryType}`);
  }
  params.push("options?: RequestOptions");

  // Build path expression (path params are URL-encoded; query params appended)
  let pathExpr = buildPathExpression(endpoint.path, pathParams);
  if (queryParams.length > 0) {
    pathExpr = `this.withQuery(${pathExpr}, query)`;
  }

  const lines: string[] = [];

  // JSDoc
  if (endpoint.summary) {
    lines.push("");
    lines.push(`  /** ${sanitizeComment(endpoint.summary)} */`);
  }

  lines.push(`  async ${methodName}(${params.join(", ")}): Promise<${returnType}> {`);

  // Method body
  if (httpMethod === "delete") {
    lines.push(`    return this.delete(${pathExpr}, options);`);
  } else if (acceptsBody) {
    // Body-less POST/PUT/PATCH still need the body slot so options lands in the right place.
    lines.push(
      `    return this.${httpMethod}<${returnType}>(${pathExpr}, ${hasBody ? "body" : "undefined"}, options);`,
    );
  } else {
    lines.push(`    return this.${httpMethod}<${returnType}>(${pathExpr}, options);`);
  }

  lines.push("  }");

  return lines;
}

function deriveMethodName(endpoint: ParsedEndpoint): string {
  if (endpoint.operationId) {
    const fromId = toCamelCase(endpoint.operationId);
    if (/^[A-Za-z_$]/.test(fromId)) return fromId;
    if (fromId !== "") return `op${toPascalCase(fromId)}`;
  }
  // Generate from method + path: GET /students/{id} → getStudentsById
  const segments = endpoint.path
    .split("/")
    .filter(Boolean)
    .map((s) => {
      if (s.startsWith("{") && s.endsWith("}")) {
        return "By" + toPascalCase(s.slice(1, -1));
      }
      return toPascalCase(s);
    });
  return toCamelCase(endpoint.method + segments.join(""));
}

function deriveReturnType(endpoint: ParsedEndpoint): string {
  if (endpoint.method === "delete") return "void";
  if (!endpoint.responseSchema) return "unknown";

  const schema = endpoint.responseSchema;
  if (schema.ref) return toPascalCase(schema.ref);
  if (schema.type === "array") {
    const itemType = schema.items?.ref
      ? toPascalCase(schema.items.ref)
      : schema.items
        ? schemaToTsType(schema.items)
        : "unknown";
    return `${itemType}[]`;
  }
  return schemaToTsType(schema);
}

/**
 * Characters allowed in a spec path: RFC 3986 path characters plus "{" "}"
 * for placeholders. Anything else (quotes, backticks, whitespace, "\\", ...)
 * is rejected rather than emitted into generated code.
 */
const SAFE_SPEC_PATH = /^\/[A-Za-z0-9._~!$&'()*+,;=:@%{}/-]*$/;

/**
 * Build the TypeScript expression for an endpoint URL path.
 *
 * Static parts are emitted as JSON string literals and path parameters as
 * `encodeURIComponent(String(param))`, joined with "+". Spec text is never
 * spliced into a template literal, so a malicious path such as
 * `/x"+require("child_process")...` or `/\${evil}` cannot become code.
 */
function buildPathExpression(path: string, pathParams: { name: string }[]): string {
  if (!SAFE_SPEC_PATH.test(path)) {
    throw new Error(`Unsafe characters in spec path ${JSON.stringify(path)}`);
  }
  const parts: string[] = [];
  let last = 0;
  for (const match of path.matchAll(/\{([^{}]+)\}/g)) {
    const name = match[1] as string;
    const param = pathParams.find((p) => p.name === name);
    if (!param) continue; // parser synthesizes missing params; leave literal otherwise
    const index = match.index ?? 0;
    if (index > last) parts.push(JSON.stringify(path.slice(last, index)));
    parts.push(`encodeURIComponent(String(${toIdentifier(param.name)}))`);
    last = index + match[0].length;
  }
  if (last < path.length || parts.length === 0) parts.push(JSON.stringify(path.slice(last)));
  return parts.join(" + ");
}

function buildQueryParamsType(params: { name: string; type: string; required: boolean }[]): string {
  const props = params.map((p) => {
    const opt = p.required ? "" : "?";
    return `${propertyKey(p.name)}${opt}: ${mapPrimitiveType(p.type)}`;
  });
  return `{ ${props.join("; ")} }`;
}

/** Every named schema a method signature can mention (refs at any array depth). */
function collectUsedSchemaNames(spec: ParsedSpec, names: Set<string>): void {
  const visit = (schema: ParsedSchema | undefined) => {
    for (let s = schema; s; s = s.items) {
      if (s.ref) names.add(s.ref);
    }
  };
  for (const ep of spec.endpoints) {
    visit(ep.requestBody);
    visit(ep.responseSchema);
  }
}

// ── String utilities ──

function toPascalCase(str: string): string {
  return str
    .replace(/[^a-zA-Z0-9]+/g, " ")
    .split(" ")
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
}

function toCamelCase(str: string): string {
  const pascal = toPascalCase(str);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

/** A valid TS identifier for a parameter name (e.g. "student-id" -> "studentId"). */
function toIdentifier(name: string): string {
  if (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)) return name;
  const camel = toCamelCase(name);
  return /^[A-Za-z_$]/.test(camel) ? camel : `_${camel}`;
}

/** An object-literal key, quoted when it is not a valid identifier. */
function propertyKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

/** Keep spec text from terminating a JSDoc comment or spanning lines. */
function sanitizeComment(text: string): string {
  return text
    .replace(/\*\//g, "*\\/")
    .replace(/\s*\n\s*/g, " ")
    .trim();
}

function sanitizeClassName(name: string): string {
  return toPascalCase(name.replace(/[^a-zA-Z0-9\s]/g, " "));
}
